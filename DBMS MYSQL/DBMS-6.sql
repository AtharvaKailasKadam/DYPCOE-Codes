CREATE OR REPLACE PROCEDURE proc_Grade (
p_Roll IN NUMBER,
p_Name IN VARCHAR2,
p_TotalMarks IN NUMBER
) AS
v_Class VARCHAR2(20);
BEGIN
IF p_TotalMarks <= 1500 AND p_TotalMarks >= 990 THEN
v_Class := 'Distinction';
ELSIF p_TotalMarks BETWEEN 900 AND 989 THEN
v_Class := 'First Class';
ELSIF p_TotalMarks BETWEEN 825 AND 899 THEN
v_Class := 'Higher Second Class';
ELSE
v_Class := 'No Class';
END IF;
INSERT INTO Result (Roll, Name, Class) VALUES (p_Roll, p_Name, v_Class);
COMMIT;
END;
/

BEGIN
FOR rec IN (SELECT Roll, Name, total_marks FROM Stud_Marks) LOOP
proc_Grade(rec.Roll, rec.Name, rec.total_marks);
END LOOP;
END;
