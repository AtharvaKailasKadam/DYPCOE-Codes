CREATE TABLE Stud_Marks (
Roll NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
Name VARCHAR2(50),
total_marks NUMBER
);
CREATE TABLE Result (
Roll NUMBER PRIMARY KEY,
Name VARCHAR2(50),
Class VARCHAR2(20)
);

